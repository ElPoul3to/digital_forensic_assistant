"""Air-gapped install bundle.

``dfa bundle build <dir>`` runs on a connected machine and collects everything
an offline analyst workstation needs:

- ``wheels/``: every Python dependency (all extras) plus the project wheel,
  downloaded for the *current* interpreter and platform, and ``requirements.txt``;
- ``python/``: the uv-managed CPython used here, and the ``uv`` binary;
- ``hf/``: the embedding and reranker model snapshots from the Hugging Face cache;
- ``ollama/``: the generator model's manifest and blobs from the Ollama store;
- ``data/external/``: the cached ATT&CK STIX bundles;
- ``volatility3/``: the Volatility symbol cache when present;
- ``install.sh`` and ``MANIFEST.json`` (SHA-256 of every file).

``dfa bundle install <dir>`` (or ``bash install.sh``) on the offline host
recreates the virtual environment from the wheels, restores the model caches
and writes a ``.env`` that keeps every library offline.
"""

from __future__ import annotations

import hashlib
import json
import logging
import os
import platform
import shutil
import subprocess
import sys
from datetime import UTC, datetime
from pathlib import Path

from dfa.config import PROJECT_ROOT, get_settings

log = logging.getLogger(__name__)

_INSTALL_SH = r"""#!/usr/bin/env bash
# Offline installer generated by `dfa bundle build`. Run on the air-gapped host from the bundle directory.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
TARGET="${1:-$HOME/digital_forensic_assistant}"
echo "[1/6] project -> $TARGET"
mkdir -p "$TARGET"
tar -xzf "$HERE/project.tar.gz" -C "$TARGET"
PY="$(ls -d "$HERE"/python/cpython-* 2>/dev/null | head -1)"
if [ -n "$PY" ]; then PYBIN="$PY/bin/python3"; else PYBIN="$(command -v python3)"; fi
echo "[2/6] virtual environment with $PYBIN"
"$PYBIN" -m venv "$TARGET/.venv"
"$TARGET/.venv/bin/python" -m pip install --no-index --find-links "$HERE/wheels" --upgrade pip >/dev/null 2>&1 || true
"$TARGET/.venv/bin/python" -m pip install --no-index --find-links "$HERE/wheels" -r "$HERE/requirements.txt"
"$TARGET/.venv/bin/python" -m pip install --no-index --find-links "$HERE/wheels" "$HERE"/wheels/digital_forensic_assistant-*.whl
echo "[3/6] Hugging Face models -> ~/.cache/huggingface/hub"
mkdir -p "$HOME/.cache/huggingface/hub"; cp -rn "$HERE"/hf/* "$HOME/.cache/huggingface/hub/" 2>/dev/null || true
echo "[4/6] Ollama model -> ${OLLAMA_MODELS:-$HOME/.ollama/models}"
OM="${OLLAMA_MODELS:-$HOME/.ollama/models}"; mkdir -p "$OM"; cp -rn "$HERE"/ollama/* "$OM/" 2>/dev/null || true
echo "[5/6] external knowledge + Volatility symbols"
mkdir -p "$TARGET/data/external"; cp -rn "$HERE"/data/external/* "$TARGET/data/external/" 2>/dev/null || true
if [ -d "$HERE/volatility3" ]; then mkdir -p "$HOME/.cache/volatility3"; cp -rn "$HERE"/volatility3/* "$HOME/.cache/volatility3/" 2>/dev/null || true; fi
echo "[6/6] offline .env"
cat >> "$TARGET/.env" <<EOF
HF_HUB_OFFLINE=1
TRANSFORMERS_OFFLINE=1
DFA_VOL_OFFLINE=1
EOF
echo
echo "Done. Next steps on this host:"
echo "  ollama serve &                        # then: ollama list  (the model should be present)"
echo "  cd $TARGET && .venv/bin/dfa smoke      # embed, store, search, LLM ping"
echo "  .venv/bin/dfa external update-attack --file data/external/attack/enterprise-attack.json"
"""


def _sha256(p: Path) -> str:
    h = hashlib.sha256()
    with p.open("rb") as fh:
        for block in iter(lambda: fh.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def _copytree(src: Path, dst: Path, what: str) -> int:
    if not src.exists():
        log.warning("%s: %s not found, skipped", what, src)
        return 0
    dst.parent.mkdir(parents=True, exist_ok=True)
    if src.is_dir():
        shutil.copytree(src, dst, dirs_exist_ok=True, symlinks=False)
    else:
        shutil.copy2(src, dst)
    return sum(f.stat().st_size for f in dst.rglob("*") if f.is_file()) if dst.is_dir() else dst.stat().st_size


def _hf_models(out: Path) -> list[str]:
    s = get_settings()
    hub = Path(os.environ.get("HF_HOME", Path.home() / ".cache" / "huggingface")) / "hub"
    if os.environ.get("HF_HUB_CACHE"):
        hub = Path(os.environ["HF_HUB_CACHE"])
    copied = []
    for name in {s.embedding.model, s.reranker.model}:
        d = hub / ("models--" + name.replace("/", "--"))
        if _copytree(d, out / "hf" / d.name, f"HF model {name}"):
            copied.append(name)
    return copied


def _ollama_model(out: Path) -> dict:
    """Copy the generator's manifest and the blobs it references."""
    s = get_settings()
    model = s.generator.model
    candidates = [Path(os.environ["OLLAMA_MODELS"])] if os.environ.get("OLLAMA_MODELS") else []
    candidates += [Path.home() / ".ollama" / "models", Path("/usr/share/ollama/.ollama/models"), Path("/var/lib/ollama/.ollama/models")]
    name, _, tag = model.partition(":")
    tag = tag or "latest"
    if "/" not in name:
        name = f"library/{name}"
    if not name.count("/") >= 2:
        name = f"registry.ollama.ai/{name}"
    for root in candidates:
        manifest = root / "manifests" / name / tag
        if manifest.exists():
            data = json.loads(manifest.read_text())
            digests = [layer["digest"] for layer in data.get("layers", [])] + ([data["config"]["digest"]] if data.get("config") else [])
            dst_manifest = out / "ollama" / "manifests" / name / tag
            dst_manifest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(manifest, dst_manifest)
            total = 0
            for dg in digests:
                blob = root / "blobs" / dg.replace(":", "-")
                if blob.exists():
                    total += _copytree(blob, out / "ollama" / "blobs" / blob.name, "ollama blob")
                else:
                    log.warning("blob %s missing under %s", dg, root)
            return {"model": model, "store": str(root), "blobs": len(digests), "bytes": total}
    log.warning("Ollama model %s not found in %s (pull it first: ollama pull %s)", model, [str(c) for c in candidates], model)
    return {"model": model, "store": None, "blobs": 0, "bytes": 0}


def _python(out: Path) -> dict:
    info: dict = {"version": platform.python_version(), "platform": platform.platform()}
    uv = shutil.which("uv")
    if uv:
        shutil.copy2(uv, out / "uv")
        info["uv"] = True
    base = Path(sys.base_prefix)
    if "uv/python" in str(base) or (base.parent.name == "python" and base.parent.parent.name == "uv"):
        info["bytes"] = _copytree(base, out / "python" / base.name, "python runtime")
    else:
        log.warning("interpreter %s is not uv-managed; the offline host needs its own Python %s", base, info["version"])
    return info


def build(out: Path, *, with_python: bool = True, with_models: bool = True) -> dict:
    out = out.resolve()
    out.mkdir(parents=True, exist_ok=True)
    report: dict = {"created": datetime.now(UTC).isoformat(), "python": None, "hf_models": [], "ollama": None, "wheels": 0}
    wheels = out / "wheels"
    wheels.mkdir(exist_ok=True)
    req = out / "requirements.txt"
    log.info("exporting the locked requirements")
    subprocess.run(["uv", "export", "--frozen", "--all-extras", "--no-hashes", "--no-emit-project", "-o", str(req)], cwd=PROJECT_ROOT, check=True)
    log.info("building the project wheel")
    subprocess.run(["uv", "build", "--wheel", "-o", str(wheels)], cwd=PROJECT_ROOT, check=True, capture_output=True)
    log.info("downloading dependency wheels (this needs network)")
    subprocess.run([sys.executable, "-m", "pip", "download", "-r", str(req), "-d", str(wheels), "--prefer-binary", "pip", "setuptools", "wheel"],
                   cwd=PROJECT_ROOT, check=True)
    report["wheels"] = len(list(wheels.glob("*")))
    log.info("packing the project sources")
    subprocess.run(["tar", "-czf", str(out / "project.tar.gz"), "--exclude=.venv", "--exclude=data/qdrant", "--exclude=data/cases", "--exclude=data/timeline",
                    "--exclude=data/audit", "--exclude=data/keys", "--exclude=data/auth", "--exclude=.git", "--exclude=__pycache__", "-C", str(PROJECT_ROOT),
                    "README.md", "pyproject.toml", "uv.lock", "Makefile", "LICENSE", ".env.example", "config", "src", "eval", "tests"], check=True)
    _copytree(get_settings().data_dir / "external", out / "data" / "external", "external knowledge")
    if with_python:
        report["python"] = _python(out)
    if with_models:
        report["hf_models"] = _hf_models(out)
        report["ollama"] = _ollama_model(out)
    vol_cache = Path.home() / ".cache" / "volatility3"
    if vol_cache.exists():
        _copytree(vol_cache, out / "volatility3", "volatility symbol cache")
    (out / "install.sh").write_text(_INSTALL_SH)
    (out / "install.sh").chmod(0o755)
    manifest = {"files": {}, "report": report}
    for f in sorted(out.rglob("*")):
        if f.is_file() and f.name != "MANIFEST.json":
            manifest["files"][str(f.relative_to(out))] = {"sha256": _sha256(f), "bytes": f.stat().st_size}
    (out / "MANIFEST.json").write_text(json.dumps(manifest, indent=1))
    report["bytes"] = sum(v["bytes"] for v in manifest["files"].values())
    report["files"] = len(manifest["files"])
    return report


def verify(bundle: Path) -> list[str]:
    """Return the files whose SHA-256 differs from MANIFEST.json (empty = intact)."""
    m = json.loads((bundle / "MANIFEST.json").read_text())
    bad = []
    for rel, info in m["files"].items():
        f = bundle / rel
        if not f.exists() or _sha256(f) != info["sha256"]:
            bad.append(rel)
    return bad


def install(bundle: Path, target: Path) -> int:
    bad = verify(bundle)
    if bad:
        raise RuntimeError(f"bundle integrity check failed for: {', '.join(bad[:10])}")
    return subprocess.run(["bash", str(bundle / "install.sh"), str(target)], check=False).returncode
